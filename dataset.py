class Dataset:
    def __init__(self, raw):
        for k, v in raw.items():
            setattr(self, k, v)
        self.temp_series = raw["tempSeries"]
        self.pm_grid = raw["pmGrid"]
        self.crime_grid = raw["crimeGrid"]
        self.csv_text = raw["csvSample"]

    def write_csv_files(self, folder="."):
        """把城市、站点、省份和天气样例写成 CSV 文件(cities.csv / stations.csv / provinces.csv / weather.csv)。"""
        import csv, os
        specs = [("cities.csv", self.cities, ["name", "lon", "lat", "pop", "region"]),
                 ("stations.csv", self.stations, ["id", "name", "lon", "lat", "pm25", "temp", "city"]),
                 ("provinces.csv", self.provinces, ["name", "centerLon", "centerLat", "area"])]
        for name, rows, cols in specs:
            with open(os.path.join(folder, name), "w", newline="", encoding="utf-8") as f:
                w = csv.writer(f)
                w.writerow(cols)
                for r in rows:
                    w.writerow([r.get(c, "") for c in cols])
        with open(os.path.join(folder, "weather.csv"), "w", encoding="utf-8") as f:
            f.write(self.csv_text + "\n")


